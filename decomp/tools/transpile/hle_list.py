# Which ARM9 functions are replaced by HLE (high-level emulation) in the port instead of being translated:
#  - CPU-state code (mrs/msr/mcr/mrc/swi/swp: interrupt flags, context switches, BIOS calls)
#  - the ARM9<->ARM7 link (IPC sync/FIFO registers): the ARM7 services are emulated by HLE layers
#  - the runtime division helpers (computed jumps into unrolled loops) and OS_Terminate
#  - OS_RescheduleThread (thread switch = Godot thread baton, DSMachine) and OS_Halt (time passes)
# Everything else, including the NitroSDK, is translated and runs against the emulated hardware registers.
import os, sys
# work directory layout (see run.sh): ghidra/{funcs.txt,funcs.json,out/,icall_overrides.txt}, ext/arm9.bin
os.chdir(os.environ.get("TRANSPILE_WORK", "."))
sys.path.insert(0, os.environ.get("CAPSTONE_PY", "/home/claude/tools/cs/bindings/python"))

import json, re, struct, sys, bisect
from capstone import *
idx = json.load(open('ghidra/funcs.json'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import image
starts = sorted(int(k, 16) for k in idx)
hle = set()
md = Cs(CS_ARCH_ARM, CS_MODE_ARM); md.skipdata = True
# function extents: from start to next start
for base, data, code in image.segments():
    for i in md.disasm(data, base):
        if i.id == 0:
            continue
        m = i.mnemonic
        if m in ('mrs', 'msr') or \
                (m == 'mcr' and 'c7, c0, #4' not in i.op_str and 'c7, c1' not in i.op_str
                 and 'c7, c5' not in i.op_str and 'c7, c6' not in i.op_str and 'c7, c10' not in i.op_str
                 and 'c7, c14' not in i.op_str) or m == 'mrc':
            j = bisect.bisect_right(starts, i.address) - 1
            if j >= 0:
                hle.add(starts[j])
        # ARM BIOS calls are `swi #n<<16`
        if m in ('svc', 'swi'):
            j = bisect.bisect_right(starts, i.address) - 1
            if j >= 0:
                k = starts[j]
                src = idx.get(f"{k:08x}", "")
                if 'swi(' in src or 'software_interrupt' in src:
                    hle.add(k)
# Thumb BIOS wrappers (`swi #n; bx lr`) are not found by the ARM-mode scan above
for k, v in idx.items():
    if 'software_interrupt(' in v or 'swi(' in v:
        hle.add(int(k, 16))


def word(a):
    return image.word(a)


IPC = set()   # the IPC FIFO registers are emulated (ds_core_base.gd + ds_arm7.gd), PXI code is translated
for k, v in idx.items():
    for m in set(re.findall(r'DAT_([0-9a-f]{8})', v)):
        a = int(m, 16)
        if image.in_code(a) and word(a) in IPC:
            hle.add(int(k, 16))
RUNTIME7 = set(int(x, 16) for x in os.environ.get("HLE7", "").split(",") if x)   # ARM7: OS services (run7.sh)
RUNTIME = RUNTIME7 if image.TARGET == "arm7" else {0x200077e, 0x20b1a2c, 0x20a9f40, 0x20ab3d0, 0x20b5e30, 0x20b603c, 0x20b6044, 0x20b5c28, 0x20b5c34, 0x20b5c70, 0x20b5c80, 0x20ab3e8}
hle |= RUNTIME
hle = sorted(a for a in hle if f"{a:08x}" in idx)
open('hle_functions.txt', 'w').write('\n'.join(f"{a:08x}" for a in hle) + '\n')
open(os.path.join(os.environ.get('REPO', 'repo'), 'decomp/notes/hle_functions%s.txt' % ('7' if image.TARGET == 'arm7' else '')), 'w').write(
    "# ARM9 functions replaced by HLE in the port (generated by hle_list.py; see decomp/notes)\n" +
    '\n'.join(f"{a:08x}" for a in hle) + '\n')
print(len(hle), 'HLE functions:', ' '.join(f"{a:08x}" for a in hle))
